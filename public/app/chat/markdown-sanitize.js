import createDOMPurify from "../vendor/dompurify-3.4.16/purify.js";

/* DOMPurify (Cure53/contributors, Apache-2.0) supplies a second boundary after
   markdown-it. OpenClaw's MIT allow-list approach informed this smaller list.
   Chart SVG and sealed Mermaid frames are generated by Branch, outside this
   ordinary Markdown vocabulary; raw reply HTML cannot request either. */
const sanitizer = createDOMPurify(window);
sanitizer.setConfig({
  ALLOWED_TAGS: ["a", "b", "blockquote", "br", "button", "code", "del", "div", "em", "h1", "h2", "h3", "h4", "h5", "h6", "hr", "i", "li", "ol", "p", "pre", "s", "span", "strong", "table", "tbody", "td", "th", "thead", "tr", "ul"],
  ALLOWED_ATTR: ["align", "class", "href", "rel", "target", "title", "start", "type", "aria-label", "data-branch-card", "data-act", "data-code-json"],
  ALLOW_DATA_ATTR: false,
  ALLOW_ARIA_ATTR: false,
});

sanitizer.addHook("beforeSanitizeAttributes", (node) => {
  if (!["TD", "TH"].includes(node.nodeName)) return;
  const match = /^text-align:(left|center|right);?$/.exec(node.getAttribute("style") ?? "");
  if (match) node.setAttribute("align", match[1]);
});

sanitizer.addHook("afterSanitizeAttributes", (node) => {
  if (node.hasAttribute("data-act") && (node.nodeName !== "BUTTON" || node.getAttribute("data-act") !== "code-copy14")) {
    node.removeAttribute("data-act");
    node.removeAttribute("data-code-json");
  }
  if (node.nodeName !== "A") return;
  const href = node.getAttribute("href");
  try {
    if (!["http:", "https:", "mailto:"].includes(new URL(href).protocol)) throw new Error("Unsupported link");
    node.setAttribute("target", "_blank");
    node.setAttribute("rel", "noopener noreferrer");
  } catch { node.removeAttribute("href"); node.removeAttribute("target"); node.removeAttribute("rel"); }
});

export const sanitizeMarkdown = (html) => sanitizer.sanitize(html);
