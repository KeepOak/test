export const SAMPLE_ID = "0f0f0f0f-0f0f-4f0f-8f0f-0f0f0f0f0f0f";

/** What a table entry says: its kind and the methods that change something there. */
export function entry(value) {
  const [kind, methods = ""] = value.split(" ");
  return { kind, methods: methods ? methods.split(",") : [] };
}

/** Turns a route written in the code (a path, or a regular expression's source) into the addresses it stands for. */
export function expandRoute(literal) {
  const text = literal.replace(/^\^/, "").replace(/\(\\\/\|\$\)$/, "")
    .replace(/\$$/, "").replace(/\$(?=\))/g, "")
    .replace(/\$\{(id|idPattern)\}/g, "[a-f0-9-]{36}")
    .replace(/\\\//g, "/").replace(/\\\./g, ".");
  return expand(text).map((path) => path.replaceAll(SAMPLE_ID, ":id"));
}
const PIECES = [
  [/^\(\[a-f0-9-\]\{36\}\)|^\[a-f0-9-\]\{36\}/, SAMPLE_ID],
  [/^\(\[a-z\]\[a-z0-9_?-\]\{0,\d+\}\)/, "sample"],
  [/^\(\[a-z0-9-\]\{1,40\}\)/, "default"],
  [/^\(\[\^\/\]\{1,\d+\}\)/, "sample"],
  [/^\(\[A-Z\]\[A-Z0-9_\]\{0,63\}\)/, "SAMPLE"],
];
function expand(text) {
  if (!text) return [""];
  for (const [pattern, value] of PIECES) {
    const found = pattern.exec(text);
    if (found) return expand(text.slice(found[0].length)).map((rest) => value + rest);
  }
  if (!text.startsWith("(")) return expand(text.slice(1)).map((rest) => text[0] + rest);
  const end = closing(text), optional = text[end + 1] === "?";
  const inner = text.slice(1, end).replace(/^\?:/, "");
  const options = [...alternatives(inner).flatMap(expand), ...(optional ? [""] : [])];
  const rest = expand(text.slice(end + (optional ? 2 : 1)));
  return options.flatMap((option) => rest.map((tail) => option + tail));
}
function closing(text) {
  let depth = 0;
  for (let i = 0; i < text.length; i++) {
    if (text[i] === "\\") { i++; continue; }
    if (text[i] === "(") depth++;
    if (text[i] === ")" && --depth === 0) return i;
  }
  throw new Error(`Unbalanced group in ${text}`);
}
function alternatives(text) {
  const parts = [];
  let depth = 0, last = 0;
  for (let i = 0; i < text.length; i++) {
    if (text[i] === "(") depth++;
    else if (text[i] === ")") depth--;
    else if (text[i] === "|" && depth === 0) { parts.push(text.slice(last, i)); last = i + 1; }
  }
  return [...parts, text.slice(last)];
}

/** The route literals written in one source file: quoted paths and regular expressions on paths. */
export function routeLiterals(code) {
  const lines = code.split("\n").filter((line) => !/^\s*(\/\/|\/\*|\*)/.test(line)).join("\n");
  const found = [];
  for (const match of lines.matchAll(/["'`](\^?\/(?:api|v1|ap|a2a|mcp)(?:[/.][^"'`\s]*)?)["'`]/g)) found.push(match[1]);
  for (const match of lines.matchAll(/\/\^\\\/(?:api|v1|ap)/g)) {
    const literal = regexSource(lines, match.index);
    if (literal) found.push(literal);
  }
  return found;
}
function regexSource(text, start) {
  let inClass = false;
  for (let i = start + 1; i < text.length; i++) {
    const c = text[i];
    if (c === "\\") { i++; continue; }
    if (c === "\n") return null;
    if (c === "[") inClass = true;
    else if (c === "]") inClass = false;
    else if (c === "/" && !inClass) return text.slice(start + 1, i);
  }
  return null;
}
